import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
// Bundle the upstream package so its extensionless ESM imports also work in Node.
const compiled = await build({
  stdin: {
    contents:
      "export { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors } from '@material/material-color-utilities';",
    resolveDir: fileURLToPath(new URL("..", import.meta.url)),
    loader: "js",
  },
  bundle: true,
  write: false,
  platform: "node",
  format: "esm",
});
const {
  argbFromHex,
  hexFromArgb,
  Hct,
  SchemeTonalSpot,
  MaterialDynamicColors,
} = await import(
  `data:text/javascript;base64,${Buffer.from(compiled.outputFiles[0].text).toString("base64")}`
);
const seed = process.argv[2] || "#6750a4";
const materialColors = new MaterialDynamicColors();
const roles = [
  ...materialColors.allColors,
  materialColors.shadow(),
  materialColors.scrim(),
  materialColors.surfaceVariant(),
];
let css = `/* Generated by Google's Material Color Utilities. Source: ${seed}, Tonal Spot.\n * Regenerate: npm run theme:generate -- '#6750a4' */\n`;
for (const dark of [false, true]) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
  css += `${dark ? ':root[data-theme="dark"]' : ':root, :root[data-theme="light"]'} {\n  color-scheme: ${dark ? "dark" : "light"};\n`;
  for (const role of roles) {
    const hex = hexFromArgb(role.getArgb(scheme));
    const name = role.name.replaceAll("_", "-");
    const rgb = [1, 3, 5]
      .map((start) => parseInt(hex.slice(start, start + 2), 16))
      .join(" ");
    css += `  --md-sys-color-${name}: ${hex};\n  --md-sys-color-${name}-rgb: ${rgb};\n`;
  }
  css += "}\n";
}
await writeFile(
  new URL("../src/theme/material-colors.css", import.meta.url),
  css,
);
process.stdout.write("Generated Material 3 light and dark color roles.\n");
